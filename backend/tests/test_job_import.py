def test_importing_gcode_stores_bytes_by_their_sha256_content_identity(
    tmp_path: Path,
) -> None:
    content = b"; generated by test slicer\nG28\nG1 X10 Y10\n"
    storage = jobs.FileSystemStorage(tmp_path)
    service = jobs.ImportService(storage=storage)

    imported = cast(
        dict[str, Any],
        service.import_gcode(
            filename="calibration-cube.gcode",
            media_type="text/x.gcode",
            content=content,
        ),
    )

    artifact_id = imported["artifact"]["id"]
    assert artifact_id == f"sha256:{hashlib.sha256(content).hexdigest()}"
    assert storage.retrieve(artifact_id) == content


def test_retrieving_a_tampered_filesystem_artifact_detects_the_sha256_mismatch(
    tmp_path: Path,
) -> None:
    storage = jobs.FileSystemStorage(tmp_path)
    artifact_id = storage.store(
        filename="calibration-cube.gcode",
        media_type="text/x.gcode",
        content=b"G28\n",
    )
    (tmp_path / artifact_id.removeprefix("sha256:")).write_bytes(b"tampered bytes\n")

    with pytest.raises(ValueError, match="sha256"):
        storage.retrieve(artifact_id)


