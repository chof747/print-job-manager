def test_import_gcode_orchestrates_injected_storage_parser_and_repository_boundaries() -> (
    None
):
    calls: list[tuple[str, object]] = []

    class FakeStorage:
        def store(self, *, filename: str, media_type: str, content: bytes) -> str:
            calls.append(("storage", (filename, media_type, content)))
            return "artifact-from-storage"

    class FakeParser:
        def parse(self, *, artifact_id: str, content: bytes) -> dict[str, object]:
            calls.append(("parser", (artifact_id, content)))
            return {"missingPlanningValues": ["material"], "diagnostics": []}

    class FakeRepository:
        @property
        def imported_artifact_ids(self) -> set[str]:
            return set()

        def save_import(
            self,
            *,
            artifact_id: str,
            filename: str,
            media_type: str,
            parsed: dict[str, object],
        ) -> None:
            calls.append(("repository", (artifact_id, filename, media_type, parsed)))

        def load_import(self, artifact_id: str) -> dict[str, object] | None:
            return None

    service = jobs.ImportService(
        storage=FakeStorage(), parser=FakeParser(), repository=FakeRepository()
    )

    imported = service.import_gcode(
        filename="part.gcode", media_type="text/x.gcode", content=b"G28\n"
    )

    assert imported == {
        "artifact": {
            "id": "artifact-from-storage",
            "filename": "part.gcode",
            "mediaType": "text/x.gcode",
        },
        "missingPlanningValues": ["material"],
        "diagnostics": [],
    }
    assert calls == [
        ("storage", ("part.gcode", "text/x.gcode", b"G28\n")),
        ("parser", ("artifact-from-storage", b"G28\n")),
        (
            "repository",
            (
                "artifact-from-storage",
                "part.gcode",
                "text/x.gcode",
                {"missingPlanningValues": ["material"], "diagnostics": []},
            ),
        ),
    ]


