import sqlalchemy as sa
from fastapi.testclient import TestClient


def test_imported_filament_weight_is_a_typed_relational_fact(
    client: TestClient,
) -> None:
    from backend.app.persistence import database

    response = client.post(
        "/api/v1/import",
        files={
            "file": (
                "cube.gcode",
                b"; generated by OrcaSlicer\n; total filament used [g] = 12.5\nG28\n",
                "text/x.gcode",
            )
        },
    )
    assert response.status_code == 201
    assert response.json()["extractedMetadata"]["filamentWeightGrams"] == 12.5

    artifact_id = response.json()["artifact"]["id"]
    created = client.post(
        f"/api/v1/import/{artifact_id}/jobs", json={"material": "PLA"}
    )
    assert created.status_code == 201

    from backend.app.api.v1 import jobs

    jobs.import_service = jobs.ImportService()
    detail = client.get(f"/api/v1/jobs/{created.json()['id']}")
    assert detail.status_code == 200
    assert (
        detail.json()["executionData"]["extractedMetadata"]["filamentWeightGrams"]
        == 12.5
    )

    with database.engine.connect() as connection:
        columns = connection.execute(
            sa.text(
                """SELECT table_name, column_name FROM information_schema.columns
                   WHERE table_schema = current_schema()
                     AND column_name ILIKE '%filament%'
                     AND data_type IN ('numeric', 'real', 'double precision')"""
            )
        ).all()
        assert columns, "filament weight must be stored in a typed numeric column"
        metadata = sa.MetaData()
        values = []
        for table_name, column_name in columns:
            table = sa.Table(table_name, metadata, autoload_with=connection)
            values.extend(connection.scalars(sa.select(table.c[column_name])).all())
        assert 12.5 in values
